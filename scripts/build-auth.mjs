// Bundle the portal's Firebase sign-in (web/src/portal-auth.js) into web/portal-auth.js: served from our own origin,
// so the portal loads no third-party script for it. Run after changing web/src/portal-auth.js or the firebase package.
import { build } from 'esbuild';
await build({
  entryPoints: ['web/src/portal-auth.js'], outfile: 'web/portal-auth.js', bundle: true, format: 'iife', minify: true,
  target: ['es2020'], legalComments: 'none', banner: { js: '/* generated by scripts/build-auth.mjs from web/src/portal-auth.js; Firebase JS SDK, Apache-2.0 */' },
});
console.log('built web/portal-auth.js');
